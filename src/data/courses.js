// 숫자 courseId(서버 ID)로 COURSES 배열을 검색해 일치하는 과목을 반환
// 예: findCourseByNumericId(3) → { id: 'english-linguistics', subject: '영어학개론', ... }
export function findCourseByNumericId(numericId) {
  return Object.values(COURSES).find(c => c.courseId === Number(numericId)) || null
}
